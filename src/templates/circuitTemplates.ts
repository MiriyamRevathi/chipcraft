export function cloneCircuitDocument(doc: CircuitDocument, newName?: string): CircuitDocument {
  const now = Date.now();
  return {
    ...doc,
    id: `circuit-${now}-${Math.random().toString(36).slice(2, 7)}`,
    name: newName ?? doc.name,
    nodes: doc.nodes.map((n) => ({ ...n, props: n.props ? { ...n.props } : undefined })),
    wires: doc.wires.map((w) => ({ ...w })),
    createdAt: now,
    updatedAt: now,
  };
}

